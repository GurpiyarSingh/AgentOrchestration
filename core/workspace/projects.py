"""Projects: the git repositories generated code is written to (ADR-008, ADR-011).

A build never touches the project's checkout directly: it runs on its own branch in a
separate git worktree, and is merged only when the user says so.
"""

from __future__ import annotations

import re
import shutil
from datetime import UTC, datetime
from pathlib import Path

from pydantic import BaseModel
from sqlalchemy import Engine
from sqlmodel import Session, col, select

from core.config import Settings
from core.models import RepositoryRecord
from core.workspace.git import GitError, commit_all, current_branch, git, is_clean, is_repo
from core.workspace.languages import get_profile

_NAME_RE = re.compile(r"^[a-zA-Z][a-zA-Z0-9_-]{1,48}$")
_SKIP_DIRS = {".git", "node_modules", "__pycache__", ".venv", ".pytest_cache"}
MAX_FILE_BYTES = 400_000


class ProjectError(ValueError):
    """Invalid project request (bad name, path, not a repo, ...)."""


class Project(BaseModel):
    """A registered project."""

    id: str
    name: str
    path: str
    language: str
    base_branch: str
    kind: str
    created_at: datetime

    @classmethod
    def of(cls, r: RepositoryRecord) -> Project:
        return cls(
            id=r.id,
            name=r.name,
            path=r.path,
            language=r.language_id or "python",
            base_branch=r.base_branch,
            kind=r.kind,
            created_at=r.created_at,
        )


class FileEntry(BaseModel):
    """A file in a project tree."""

    path: str
    size: int


def list_tree(root: Path, limit: int = 2000) -> list[FileEntry]:
    """Files under `root` (skipping VCS/dependency folders), POSIX paths, sorted."""
    out: list[FileEntry] = []
    root = root.resolve()
    for p in sorted(root.rglob("*")):
        rel = p.relative_to(root)
        if any(part in _SKIP_DIRS for part in rel.parts) or not p.is_file():
            continue
        out.append(FileEntry(path=rel.as_posix(), size=p.stat().st_size))
        if len(out) >= limit:
            break
    return out


def read_text(root: Path, rel: str) -> str:
    """Read a text file inside `root` (path-checked)."""
    root_real = root.resolve()
    target = (root_real / rel).resolve()
    if not target.is_relative_to(root_real) or ".git" in Path(rel).parts:
        raise ProjectError("Path is outside the project.")
    if not target.is_file():
        raise ProjectError(f"File not found: {rel}")
    if target.stat().st_size > MAX_FILE_BYTES:
        return f"[file too large to display: {target.stat().st_size} bytes]"
    return target.read_text(encoding="utf-8", errors="replace")


class ProjectStore:
    """Create, register, list and read projects."""

    def __init__(self, db: Engine, settings: Settings) -> None:
        self.db = db
        self.settings = settings

    @property
    def workspaces_dir(self) -> Path:
        """Folder for new projects and build worktrees."""
        return self.settings.workspaces_dir

    @property
    def author(self) -> tuple[str, str]:
        """Git identity for commits (live from settings)."""
        return (self.settings.git_author_name, self.settings.git_author_email)

    def list_all(self) -> list[Project]:
        """All projects, newest first."""
        with Session(self.db) as s:
            rows = s.exec(select(RepositoryRecord).order_by(col(RepositoryRecord.created_at).desc())).all()
            return [Project.of(r) for r in rows]

    def get(self, project_id: str) -> Project:
        """One project or ProjectError."""
        with Session(self.db) as s:
            rec = s.get(RepositoryRecord, project_id)
            if rec is None:
                raise ProjectError(f"Project '{project_id}' not found.")
            return Project.of(rec)

    def create(self, name: str, language: str, path: str | None = None) -> Project:
        """Create a new git repo with a language scaffold and register it."""
        name = name.strip()
        if not _NAME_RE.match(name):
            raise ProjectError("Name must be 2-49 characters: letters, digits, '-' or '_', starting with a letter.")
        profile = get_profile(language)
        self._ensure_unique(name)
        root = Path(path).expanduser() if path else self.workspaces_dir / name
        root = root.resolve()
        if root.exists() and any(root.iterdir()):
            raise ProjectError(f"Folder is not empty: {root}")
        root.mkdir(parents=True, exist_ok=True)
        try:
            git(root, "init", "-q", "-b", "main")
            for rel, content in {
                **profile.scaffold,
                "README.md": f"# {name}\n\nGenerated by Codeloom ({profile.name}).\n",
            }.items():
                f = root / rel
                f.parent.mkdir(parents=True, exist_ok=True)
                f.write_text(content, encoding="utf-8")
            commit_all(root, "Initial scaffold", self.author)
        except GitError:
            shutil.rmtree(root, ignore_errors=True)
            raise
        return self._register(name, "new", root, language, "main")

    def add_existing(self, name: str, language: str, path: str) -> Project:
        """Register an existing local git repository (must be clean, with at least one commit)."""
        name = name.strip()
        if not _NAME_RE.match(name):
            raise ProjectError("Name must be 2-49 characters: letters, digits, '-' or '_', starting with a letter.")
        get_profile(language)
        self._ensure_unique(name)
        root = Path(path).expanduser().resolve()
        if not root.is_dir() or not is_repo(root):
            raise ProjectError(f"Not the top folder of a git repository: {root}")
        try:
            branch = current_branch(root)
        except GitError as e:
            raise ProjectError("The repository has no commits yet.") from e
        if not is_clean(root):
            raise ProjectError("The repository has uncommitted changes; commit or stash them first.")
        return self._register(name, "local", root, language, branch)

    def remove(self, project_id: str) -> None:
        """Unregister a project (files are left on disk)."""
        with Session(self.db) as s:
            rec = s.get(RepositoryRecord, project_id)
            if rec is None:
                raise ProjectError(f"Project '{project_id}' not found.")
            s.delete(rec)
            s.commit()

    def _ensure_unique(self, name: str) -> None:
        with Session(self.db) as s:
            if s.exec(select(RepositoryRecord).where(RepositoryRecord.name == name)).first():
                raise ProjectError(f"A project named '{name}' already exists.")

    def _register(self, name: str, kind: str, root: Path, language: str, branch: str) -> Project:
        rec = RepositoryRecord(
            name=name,
            kind=kind,
            path=str(root),
            language_id=language,
            base_branch=branch,
            created_at=datetime.now(UTC),
        )
        with Session(self.db) as s:
            s.add(rec)
            s.commit()
            s.refresh(rec)
            return Project.of(rec)
